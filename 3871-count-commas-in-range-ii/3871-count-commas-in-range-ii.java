class Solution {
    public long countCommas(long n) {

        if (n < 1_000) {
            return 0;
        }

        if (n < 1_000_000) {
            return n - 999;
        }

        if (n < 1_000_000_000) {
            return (1_000_000 - 1_000)
                    + 2L * (n - 999_999);
        }

        if (n < 1_000_000_000_000L) {
            return (1_000_000 - 1_000)
                    + 2L * (1_000_000_000L - 1_000_000)
                    + 3L * (n - 999_999_999L);
        }

        if (n < 1_000_000_000_000_000L) {
            return (1_000_000 - 1_000)
                    + 2L * (1_000_000_000L - 1_000_000)
                    + 3L * (1_000_000_000_000L - 1_000_000_000L)
                    + 4L * (n - 999_999_999_999L);
        }

        return (1_000_000 - 1_000)
                + 2L * (1_000_000_000L - 1_000_000)
                + 3L * (1_000_000_000_000L - 1_000_000_000L)
                + 4L * (1_000_000_000_000_000L - 1_000_000_000_000L)
                + 5L * (n - 999_999_999_999_999L);
    }
}
